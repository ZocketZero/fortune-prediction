export function getElementOfBirthYear(yearCE: number): string {
  // Heavenly Stems 5 elements
  // Last digit of year:
  // 0, 1 = Metal (ทอง)
  // 2, 3 = Water (น้ำ)
  // 4, 5 = Wood (ไม้)
  // 6, 7 = Fire (ไฟ)
  // 8, 9 = Earth (ดิน)
  const lastDigit = Math.abs(yearCE) % 10;
  if (lastDigit === 0 || lastDigit === 1) return 'ธาตุทอง (Metal)';
  if (lastDigit === 2 || lastDigit === 3) return 'ธาตุน้ำ (Water)';
  if (lastDigit === 4 || lastDigit === 5) return 'ธาตุไม้ (Wood)';
  if (lastDigit === 6 || lastDigit === 7) return 'ธาตุไฟ (Fire)';
  return 'ธาตุดิน (Earth)';
}

export function calculateLifePathNumber(day: number, month: number, yearCE: number): LifePathNumberFortune {
  const reduceToSingleDigit = (num: number, allowMaster = true): number => {
    while (num > 9) {
      if (allowMaster && (num === 11 || num === 22 || num === 33)) {
        return num;
      }
      num = String(num)
        .split('')
        .reduce((sum, digit) => sum + parseInt(digit, 10), 0);
    }
    return num;
  };

  const dayReduced = reduceToSingleDigit(day, false);
  const monthReduced = reduceToSingleDigit(month, false);
  const yearReduced = reduceToSingleDigit(yearCE, false);

  const total = dayReduced + monthReduced + yearReduced;
  const finalNum = reduceToSingleDigit(total, true);

  return LIFE_PATH_FORTUNES[finalNum] || LIFE_PATH_FORTUNES[reduceToSingleDigit(finalNum, false)] || LIFE_PATH_FORTUNES[1];
}

export function getBirthTimePeriod(timeString?: string): BirthTimeFortune | null {
  if (!timeString) return null;
  const [hour] = timeString.split(':').map(Number);
  if (hour >= 6 && hour < 10) return BIRTH_TIME_PERIODS[0];
  if (hour >= 10 && hour < 14) return BIRTH_TIME_PERIODS[1];
  if (hour >= 14 && hour < 18) return BIRTH_TIME_PERIODS[2];
  if (hour >= 18 && hour < 22) return BIRTH_TIME_PERIODS[3];
  if (hour >= 22 || hour < 2) return BIRTH_TIME_PERIODS[4];
  return BIRTH_TIME_PERIODS[5]; // 02:00 - 05:59
}
