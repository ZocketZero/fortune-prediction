// Helper Functions for Calculating Elements & Fortunes
export function getDayOfWeekFromDate(date: Date, birthTime?: string): DayOfWeekFortune {
  const dayIndex = date.getDay(); // 0 = Sun, 1 = Mon, ..., 6 = Sat
  
  // If Wednesday, check if day or night (if time specified)
  if (dayIndex === 3) {
    if (birthTime) {
      const [hour] = birthTime.split(':').map(Number);
      if (hour >= 18 || hour < 6) {
        return DAY_OF_WEEK_FORTUNES[4]; // wednesday_night
      }
    }
    return DAY_OF_WEEK_FORTUNES[3]; // wednesday_day
  }

  const mapIndexToDay: Record<number, number> = {
    0: 0, // Sunday
    1: 1, // Monday
    2: 2, // Tuesday
    4: 5, // Thursday
    5: 6, // Friday
    6: 7  // Saturday
  };

  return DAY_OF_WEEK_FORTUNES[mapIndexToDay[dayIndex] ?? 0];
}

