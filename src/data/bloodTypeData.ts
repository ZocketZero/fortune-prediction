export const getBloodTypeFortune = (type: BloodType): BloodTypeFortune => {
  return BLOOD_TYPE_FORTUNES[type] || BLOOD_TYPE_FORTUNES.A;
};

export const getBloodCompatibility = (myType: BloodType, partnerType: BloodType): BloodCompatibility => {
  const key = `${myType}-${partnerType}`;
  if (BLOOD_COMPATIBILITY_DATA[key]) {
    return BLOOD_COMPATIBILITY_DATA[key];
  }
  const reverseKey = `${partnerType}-${myType}`;
  if (BLOOD_COMPATIBILITY_DATA[reverseKey]) {
    return {
      ...BLOOD_COMPATIBILITY_DATA[reverseKey],
      primary: myType,
      partner: partnerType,
    };
  }
  return BLOOD_COMPATIBILITY_DATA['A-A'];
};
